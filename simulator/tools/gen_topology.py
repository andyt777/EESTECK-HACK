"""Generates simulator/topology.yaml (run once; the result is committed).

    python tools/gen_topology.py topology.yaml

Schematic, not geographic: coordinates are x/y on a 1000 x 600 canvas used by
the Grid Intelligence map. Deterministic (no randomness), so the file can be
regenerated identically.
"""

from __future__ import annotations

import math

REGIONS = [
    {
        "id": "MUN",
        "name": "Muntenia",
        "center": (640, 420),
        "stations": [
            ("București Nord", "București"),
            ("București Sud", "București"),
            ("Ploiești Vest", "Prahova"),
            ("Pitești Sud", "Argeș"),
        ],
    },
    {
        "id": "BAN",
        "name": "Banat",
        "center": (200, 230),
        "stations": [
            ("Timișoara Nord", "Timiș"),
            ("Timișoara Sud", "Timiș"),
            ("Arad Est", "Arad"),
            ("Reșița", "Caraș-Severin"),
        ],
    },
    {
        "id": "DOB",
        "name": "Dobrogea",
        "center": (815, 150),
        "stations": [
            ("Constanța Nord", "Constanța"),
            ("Constanța Sud", "Constanța"),
            ("Medgidia", "Constanța"),
            ("Tulcea", "Tulcea"),
        ],
    },
]
POSTS_PER_STATION = 5


def build() -> dict:
    regions, stations, posts, lines = [], [], [], []
    for region in REGIONS:
        cx, cy = region["center"]
        regions.append({"id": region["id"], "name": region["name"], "x": cx, "y": cy})
        station_ids = []
        n = len(region["stations"])
        for i, (name, zone) in enumerate(region["stations"]):
            angle = 2 * math.pi * i / n
            sx, sy = round(cx + 110 * math.cos(angle)), round(cy + 80 * math.sin(angle))
            sid = f"ST-{region['id']}-{i + 1:02d}"
            station_ids.append(sid)
            stations.append({"id": sid, "name": name, "region": region["id"], "zone": zone,
                             "voltageKv": 110, "x": sx, "y": sy})
            for p in range(POSTS_PER_STATION):
                pangle = angle + (p - 2) * 0.35
                px, py = round(sx + 55 * math.cos(pangle)), round(sy + 45 * math.sin(pangle))
                pid = f"PT-{region['id']}-{i + 1:02d}-{p + 1:02d}"
                posts.append({"id": pid, "station": sid, "region": region["id"], "zone": zone,
                              "capacityKva": [250, 400, 630, 400, 250][p], "x": px, "y": py})
                lines.append({"from": sid, "to": pid, "kind": "MV", "voltageKv": 20})
        # 110 kV ring between the stations of a region
        for i, sid in enumerate(station_ids):
            lines.append({"from": sid, "to": station_ids[(i + 1) % n], "kind": "HV", "voltageKv": 110})
    # interconnections between regions
    lines.append({"from": "ST-BAN-01", "to": "ST-MUN-04", "kind": "HV", "voltageKv": 220})
    lines.append({"from": "ST-MUN-01", "to": "ST-DOB-03", "kind": "HV", "voltageKv": 220})
    return {"schemaVersion": 1, "dataOrigin": "SIMULATED", "canvas": {"width": 1000, "height": 600},
            "regions": regions, "stations": stations, "transformers": posts, "lines": lines}


def to_yaml(data: dict) -> str:
    out = [
        "# FileGrid PPC - simulated grid topology (schematic coordinates, not geographic).",
        "# Generated by tools/gen_topology.py; meters are assigned to these transformer posts",
        "# at start-up (deterministic, from SIM_SEED), so the file stays small.",
        f"schemaVersion: {data['schemaVersion']}",
        f"dataOrigin: {data['dataOrigin']}",
        f"canvas: {{width: {data['canvas']['width']}, height: {data['canvas']['height']}}}",
    ]
    for key in ("regions", "stations", "transformers", "lines"):
        out.append(f"{key}:")
        for item in data[key]:
            fields = ", ".join(f"{k}: {fmt(v)}" for k, v in item.items())
            out.append(f"  - {{{fields}}}")
    return "\n".join(out) + "\n"


def fmt(value) -> str:
    if isinstance(value, str):
        return '"' + value + '"'
    return str(value)


if __name__ == "__main__":
    import sys

    target = sys.argv[1] if len(sys.argv) > 1 else "topology.yaml"
    with open(target, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(to_yaml(build()))
